#!/usr/bin/env python3
# Maintainer: zhaowenbo
"""Generate PRNG-371 input streams for NIST SP 800-22.

This generator uses the PC-side golden PRNG-371 model. It intentionally refuses
non-2000 warmup values so old warmup=1000 evidence cannot be regenerated by
accident in this evidence chain.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import sys
from typing import Iterable


ROOT = Path(__file__).resolve().parents[3]
DEFAULT_SEED = (1000, 2000, 3000, 4000)
OFFICIAL_WARMUP = 2000


def load_prng_class():
    module_path = ROOT / "hw" / "src_371" / "golden_prng.py"
    spec = importlib.util.spec_from_file_location("golden_prng_371", module_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load golden PRNG module from {module_path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.ChaosPRNG371, module_path


def parse_seed(text: str) -> tuple[int, int, int, int]:
    parts = [p.strip() for p in text.replace(",", " ").split() if p.strip()]
    if len(parts) != 4:
        raise argparse.ArgumentTypeError("seed must contain four integers")
    values = tuple(int(p, 0) for p in parts)
    if any(v < 0 or v > 65535 for v in values):
        raise argparse.ArgumentTypeError("seed words must fit uint16")
    return values  # type: ignore[return-value]


def iter_bits_from_bytes(data: bytes) -> Iterable[str]:
    for byte in data:
        for bit in range(7, -1, -1):
            yield "1" if (byte >> bit) & 1 else "0"


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def read_golden_ref(path: Path, limit: int) -> list[str]:
    if not path.exists():
        return []
    rows: list[str] = []
    for line in path.read_text().splitlines():
        cleaned = line.strip().lower().replace("0x", "")
        if cleaned:
            rows.append(cleaned)
        if len(rows) >= limit:
            break
    return rows


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--num_sequences", type=int, required=True)
    parser.add_argument("--bits_per_sequence", type=int, required=True)
    parser.add_argument("--warmup", type=int, default=OFFICIAL_WARMUP)
    parser.add_argument("--seed", type=parse_seed, default=DEFAULT_SEED)
    parser.add_argument("--output_dir", type=Path, required=True)
    parser.add_argument("--format", choices=["ascii_bits", "binary"], default="ascii_bits")
    parser.add_argument("--config_json", type=Path, default=None)
    parser.add_argument("--preview_words", type=int, default=16)
    args = parser.parse_args()

    if args.warmup != OFFICIAL_WARMUP:
        raise SystemExit("Refusing to generate non-official warmup. PRNG-371 evidence chain requires warmup=2000.")
    if args.num_sequences <= 0 or args.bits_per_sequence <= 0:
        raise SystemExit("num_sequences and bits_per_sequence must be positive")

    total_bits = args.num_sequences * args.bits_per_sequence
    total_bytes = (total_bits + 7) // 8
    output_dir: Path = args.output_dir
    input_dir = output_dir / "input"
    input_dir.mkdir(parents=True, exist_ok=True)

    ChaosPRNG371, module_path = load_prng_class()
    prng = ChaosPRNG371(init_x=args.seed, warmup=args.warmup)
    data = prng.generate_bytes(total_bytes)
    if total_bits % 8:
        keep = total_bits % 8
        mask = 0xFF & (0xFF << (8 - keep))
        data = data[:-1] + bytes([data[-1] & mask])

    base = f"prng371_warmup{args.warmup}_{args.num_sequences}x{args.bits_per_sequence}"
    bin_path = input_dir / f"{base}.bin"
    bin_path.write_bytes(data)

    asc_path = input_dir / f"{base}.asc"
    if args.format == "ascii_bits":
        with asc_path.open("w", encoding="ascii") as f:
            count = 0
            for bit_char in iter_bits_from_bytes(data):
                if count >= total_bits:
                    break
                f.write(bit_char)
                count += 1
                if count % 100 == 0:
                    f.write("\n")
            if count % 100:
                f.write("\n")

    output_file = asc_path if args.format == "ascii_bits" else bin_path
    output_sha = sha256_file(output_file)
    bin_sha = sha256_file(bin_path)
    asc_sha = sha256_file(asc_path) if asc_path.exists() else None

    preview_prng = ChaosPRNG371(init_x=args.seed, warmup=args.warmup)
    preview_words = [f"{preview_prng.next():016x}" for _ in range(args.preview_words)]
    golden_ref_path = ROOT / "hw" / "src_371" / "golden_ref_371.txt"
    golden_ref_words = read_golden_ref(golden_ref_path, args.preview_words)
    golden_alignment = {
        "golden_ref_path": str(golden_ref_path),
        "checked_words": min(len(preview_words), len(golden_ref_words)),
        "match": bool(golden_ref_words) and preview_words[: len(golden_ref_words)] == golden_ref_words,
        "first_mismatch_index": None,
    }
    for idx, (a, b) in enumerate(zip(preview_words, golden_ref_words)):
        if a != b:
            golden_alignment["first_mismatch_index"] = idx
            break

    config = {
        "variant": "chaos_prng_371 / PRNG-371",
        "expansion_coefficients": [371, 373, 375],
        "coupling_coefficients": [50, 48, 46],
        "B_VAL": 111,
        "word_size": "16-bit",
        "physical_state_dimension": "4D",
        "internal_delayed_state": "6 words",
        "warmup": args.warmup,
        "seed": list(args.seed),
        "byte_order": "little-endian per 64-bit output word in golden_prng.py",
        "num_sequences": args.num_sequences,
        "bits_per_sequence": args.bits_per_sequence,
        "total_bits": total_bits,
        "total_bytes_generated": len(data),
        "format": args.format,
        "generator_module": str(module_path),
        "output_file": str(output_file),
        "binary_file": str(bin_path),
        "ascii_file": str(asc_path) if asc_path.exists() else None,
        "output_sha256": output_sha,
        "binary_sha256": bin_sha,
        "ascii_sha256": asc_sha,
        "golden_ref_alignment": golden_alignment,
    }

    config_path = args.config_json or output_dir / "config.json"
    config_path.parent.mkdir(parents=True, exist_ok=True)
    config_path.write_text(json.dumps(config, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    sha_path = output_dir / "input_sha256.txt"
    lines = [
        f"selected_output_sha256  {output_sha}  {output_file}",
        f"binary_sha256           {bin_sha}  {bin_path}",
    ]
    if asc_sha:
        lines.append(f"ascii_sha256            {asc_sha}  {asc_path}")
    sha_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    preview_path = output_dir / "first_words_preview.txt"
    with preview_path.open("w", encoding="utf-8") as f:
        f.write("# First post-warmup PRNG-371 64-bit words\n")
        for idx, word in enumerate(preview_words):
            ref = golden_ref_words[idx] if idx < len(golden_ref_words) else "N/A"
            mark = "MATCH" if ref == word else ("NO_REF" if ref == "N/A" else "MISMATCH")
            f.write(f"{idx:04d}  {word}  golden_ref={ref}  {mark}\n")

    report_path = output_dir / "GENERATION_REPORT.md"
    report_path.write_text(
        "\n".join(
            [
                "# PRNG-371 NIST Input Generation Report",
                "",
                f"- Variant: `chaos_prng_371` / PRNG-371",
                f"- Warmup: {args.warmup}",
                f"- Seed: {list(args.seed)}",
                f"- Num sequences: {args.num_sequences}",
                f"- Bits per sequence: {args.bits_per_sequence}",
                f"- Total bits: {total_bits}",
                f"- Format selected for STS: `{args.format}`",
                f"- Selected output: `{output_file}`",
                f"- Binary output: `{bin_path}`",
                f"- ASCII output: `{asc_path if asc_path.exists() else 'not generated'}`",
                f"- Selected output SHA-256: `{output_sha}`",
                f"- Binary SHA-256: `{bin_sha}`",
                f"- ASCII SHA-256: `{asc_sha}`",
                "- Byte order: little-endian per 64-bit output word.",
                "- Source: PC golden PRNG-371 model (`hw/src_371/golden_prng.py` + `golden_371.so`).",
                f"- Golden reference alignment match: `{golden_alignment['match']}`",
                "",
                "This is PC golden PRNG-371 output. It is not FPGA physical validation.",
            ]
        )
        + "\n",
        encoding="utf-8",
    )

    print(json.dumps(config, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
